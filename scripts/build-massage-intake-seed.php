<?php
declare(strict_types=1);
// Rebuild the SQL after editing the maintained JSON; no database connection.
require dirname(__DIR__).'/api/vendor/autoload.php';
use Wellness\Service\ClientFormDefinition;
$root=dirname(__DIR__);
$document=json_decode(file_get_contents($root.'/api/database/templates/massage-therapy-intake.json'),true,32,JSON_THROW_ON_ERROR);
if ($document['format']!=='wellness-form'||$document['format_version']!==1||$document['form_type']!=='intake') throw new RuntimeException('Unexpected document format');
$definition=ClientFormDefinition::definition($document['definition'],$document['form_type']);
$description='Basic bilingual massage intake: goals, relevant health history, allergies and comfort preferences. Practitioner review and separate treatment consent are required. / Bilan bilingue de base : objectifs, antécédents pertinents, allergies et préférences. Révision par le praticien et consentement au traitement distinct requis.';
$hex=fn(string $value):string=>'CONVERT(0x'.bin2hex($value).' USING utf8mb4)';
$json=json_encode($definition,JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES|JSON_THROW_ON_ERROR);
$nameSql=$hex($document['name']);$descriptionSql=$hex($description);$definitionSql=$hex($json);
$hash=hash('sha256',json_encode([$document['name'],$description,'intake',$definition],JSON_THROW_ON_ERROR));
$sql=<<<SQL
-- Generated by php scripts/build-massage-intake-seed.php; edit the JSON, then regenerate.
-- Select wellness_centre in phpMyAdmin. Requires migration 045_form_library.sql.
-- Inserts ONE GLOBAL PENDING template. Approval is performed in the portal.
-- If exactly one application administrator is active, use that account.
-- If multiple are active, replace the next SET with SET @seed_admin_id = YOUR_ID;
-- Find the ID with: SELECT id, display_name, email FROM application_administrators WHERE status='active';
SET @seed_admin_id = (SELECT IF(COUNT(*)=1,MIN(id),NULL) FROM application_administrators WHERE status='active');
-- UTF-8 hex literals keep accents and JSON escaping independent of SQL mode/client encoding.
SET @seed_name = $nameSql;
SET @seed_description = $descriptionSql;
SET @seed_definition = $definitionSql;
SET @seed_hash = '$hash';
SET @seed_entry_id = NULL;
SET @seed_version_id = NULL;
SET @seed_valid_admin = NULL;
START TRANSACTION;
-- Lock the selected active administrator; no administrator or permissions are created.
-- SET avoids phpMyAdmin appending a display LIMIT after FOR UPDATE.
SET @seed_valid_admin = (SELECT id FROM application_administrators
 WHERE id=@seed_admin_id AND status='active' FOR UPDATE);
SET @seed_reset_insert_id = LAST_INSERT_ID(0);
INSERT INTO form_library_entries(scope,created_by_admin_id,creation_key,creation_actor,creation_hash)
 SELECT 'global',@seed_valid_admin,'massage-therapy-intake-v1','seed:starter-library',@seed_hash
 WHERE @seed_valid_admin IS NOT NULL
 -- Leave the existing ID unchanged and clear the insert marker on a duplicate.
 ON DUPLICATE KEY UPDATE id=id+LAST_INSERT_ID(0);
SET @seed_created = (LAST_INSERT_ID()<>0);
SET @seed_entry_id = (SELECT id FROM form_library_entries
 WHERE creation_actor='seed:starter-library' AND creation_key='massage-therapy-intake-v1' FOR UPDATE);
INSERT INTO form_library_versions(entry_id,version,name,description,form_type,definition,request_key,request_hash)
 SELECT @seed_entry_id,1,@seed_name,@seed_description,'intake',@seed_definition,'massage-therapy-intake-v1',@seed_hash
 WHERE @seed_created=1 AND @seed_valid_admin IS NOT NULL;
SET @seed_version_id = (SELECT id FROM form_library_versions WHERE entry_id=@seed_entry_id AND version=1);
INSERT INTO form_library_events(version_id,actor_admin_id,action,correlation_id,metadata)
 SELECT @seed_version_id,@seed_valid_admin,'submit','seed:massage-therapy-intake-v1','{"source":"massage-therapy-intake.json","seed_version":1}'
 WHERE @seed_created=1 AND @seed_valid_admin IS NOT NULL;
COMMIT;
SELECT CASE
 WHEN @seed_valid_admin IS NULL THEN 'STOP: select an existing active application administrator ID and rerun'
 WHEN @seed_version_id IS NULL THEN 'STOP: existing seed entry is incomplete - investigate without deleting or overwriting it'
 WHEN @seed_created=1 THEN 'CREATED: pending global template - review and approve in application administration'
 ELSE 'UNCHANGED: starter already exists - its content, revisions, approval and retirement were preserved'
 END AS result,@seed_entry_id AS entry_id,@seed_version_id AS initial_version_id;
-- Stop on any SQL error. If an import stops before COMMIT, run ROLLBACK in that session.
SQL;
$sql=str_replace("\r\n","\n",$sql)."\n";
$path=$root.'/api/database/templates/seed-massage-therapy-intake.sql';
if (in_array('--check',$argv,true)) {
    if (!is_file($path)||str_replace("\r\n","\n",file_get_contents($path))!==$sql) throw new RuntimeException('Seed SQL differs from JSON; regenerate it');
    echo 'JSON validates; generated SQL matches ('.count($definition['questions'])." bilingual questions).\n";
} else {
    file_put_contents($path,$sql);
    echo "Wrote $path\n";
}
